import { getModel, judgeModel, MODEL_REGISTRY } from "./model.ai.js";

interface BattleResult {
    problem: string;
    model1_id: string;
    model2_id: string;
    model1_name: string;
    model2_name: string;
    solution_1: string;
    solution_2: string;
    judge: {
        solution_1_score: number;
        solution_2_score: number;
        solution_1_reasoning: string;
        solution_2_reasoning: string;
    };
    timestamp: number;
}

// In-memory storage for history and leaderboard
const battleHistory: BattleResult[] = [];
const leaderboard: Record<string, { wins: number; losses: number; draws: number; totalScore: number; battles: number }> = {};

function updateLeaderboard(result: BattleResult) {
    const { model1_id, model2_id } = result;
    const s1 = result.judge.solution_1_score;
    const s2 = result.judge.solution_2_score;

    // Ensure both leaderboard entries exist.
    for (const id of [model1_id, model2_id]) {
        if (!leaderboard[id]) {
            leaderboard[id] = {
                wins: 0,
                losses: 0,
                draws: 0,
                totalScore: 0,
                battles: 0,
            };
        }
    }

    // Store references so TypeScript can safely track the entries.
    const model1 = leaderboard[model1_id];
    const model2 = leaderboard[model2_id];

    if (!model1 || !model2) {
        throw new Error("Failed to initialize leaderboard entries");
    }

    model1.totalScore += s1;
    model1.battles += 1;

    model2.totalScore += s2;
    model2.battles += 1;

    if (s1 > s2) {
        model1.wins += 1;
        model2.losses += 1;
    } else if (s2 > s1) {
        model2.wins += 1;
        model1.losses += 1;
    } else {
        model1.draws += 1;
        model2.draws += 1;
    }
}
export function getHistory() {
    return battleHistory;
}

export function getLeaderboard() {
    return Object.entries(leaderboard).map(([modelId, stats]) => ({
        modelId,
        modelName: MODEL_REGISTRY[modelId]?.name || modelId,
        ...stats,
        matches: battleHistory
            .filter((battle) => battle.model1_id === modelId || battle.model2_id === modelId)
            .map((battle) => {
                const isModel1 = battle.model1_id === modelId;
                const modelScore = isModel1 ? battle.judge.solution_1_score : battle.judge.solution_2_score;
                const opponentScore = isModel1 ? battle.judge.solution_2_score : battle.judge.solution_1_score;
                return {
                    problem: battle.problem,
                    opponent: isModel1 ? battle.model2_name : battle.model1_name,
                    modelScore,
                    opponentScore,
                    outcome: modelScore > opponentScore ? "win" : modelScore < opponentScore ? "loss" : "draw",
                    timestamp: battle.timestamp,
                };
            })
            .sort((a, b) => b.timestamp - a.timestamp),
        avgScore: stats.battles > 0 ? (stats.totalScore / stats.battles).toFixed(1) : "0",
    })).sort((a, b) => b.wins - a.wins || parseFloat(b.avgScore) - parseFloat(a.avgScore));
}

export function getAvailableModels() {
    return Object.entries(MODEL_REGISTRY).map(([id, info]) => ({
        id,
        name: info.name,
        provider: info.provider,
    }));
}

export default async function battle(problem: string, model1Id: string, model2Id: string) {
    const model1 = getModel(model1Id);
    const model2 = getModel(model2Id);

    // Get solutions
    let solution1 = "";
    let solution2 = "";

    try {
        const res1 = await model1.invoke(problem);
        solution1 = res1.text;
    } catch (error: any) {
        console.error(`${model1Id} failed:`, error.message);
        solution1 = `${MODEL_REGISTRY[model1Id]?.name || model1Id} is currently unavailable.`;
    }

    try {
        const res2 = await model2.invoke(problem);
        solution2 = res2.text;
    } catch (error: any) {
        console.error(`${model2Id} failed:`, error.message);
        solution2 = `${MODEL_REGISTRY[model2Id]?.name || model2Id} is currently unavailable.`;
    }

    // Judge
    const judgePrompt = `You are a judge tasked with evaluating two solutions generated by different AI models. Please provide a score out of 10 for each solution, along with your reasoning for the scores.
Return ONLY a valid JSON object in this exact format (do not include markdown block ticks like \`\`\`json):
{
    "solution_1_score": 9,
    "solution_2_score": 8,
    "solution_1_reasoning": "Reason 1...",
    "solution_2_reasoning": "Reason 2..."
}

Problem: ${problem}

Solution 1 (by ${MODEL_REGISTRY[model1Id]?.name || model1Id}): ${solution1}

Solution 2 (by ${MODEL_REGISTRY[model2Id]?.name || model2Id}): ${solution2}
`;

    let judge = {
        solution_1_score: 0,
        solution_2_score: 0,
        solution_1_reasoning: "Judge unavailable.",
        solution_2_reasoning: "Judge unavailable.",
    };

    try {
        const response = await judgeModel.invoke(judgePrompt);
        let text = response.content || response.text || "";
        if (typeof text !== 'string') text = JSON.stringify(text);

        const match = text.match(/\{[\s\S]*\}/);
        if (match) {
            try {
                const parsed = JSON.parse(match[0]);
                judge = {
                    solution_1_score: Number(parsed.solution_1_score) || 0,
                    solution_2_score: Number(parsed.solution_2_score) || 0,
                    solution_1_reasoning: parsed.solution_1_reasoning || "N/A",
                    solution_2_reasoning: parsed.solution_2_reasoning || "N/A",
                };
            } catch (e) {
                console.error("JSON parse error from Judge:", e);
            }
        }
    } catch (error: any) {
        console.error("Judge failed:", error.message);
    }

    const result: BattleResult = {
        problem,
        model1_id: model1Id,
        model2_id: model2Id,
        model1_name: MODEL_REGISTRY[model1Id]?.name || model1Id,
        model2_name: MODEL_REGISTRY[model2Id]?.name || model2Id,
        solution_1: solution1,
        solution_2: solution2,
        judge,
        timestamp: Date.now(),
    };

    battleHistory.push(result);
    updateLeaderboard(result);

    return result;
}